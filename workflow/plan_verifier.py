class DecisionGateResult:
    """Result from the human Decision Gate."""

    def __init__(self, decision: str, reason: str = "") -> None:
        if decision not in ("approve", "revise", "reject"):
            raise ValueError(f"Invalid decision: {decision}. Must be approve/revise/reject.")
        self.decision = decision
        self.reason = reason

    @property
    def approved(self) -> bool:
        return self.decision == "approve"

    @property
    def needs_revision(self) -> bool:
        return self.decision == "revise"

    @property
    def rejected(self) -> bool:
        return self.decision == "reject"

    def __repr__(self) -> str:
        return f"DecisionGateResult(decision={self.decision!r}, reason={self.reason!r})"


def _print_plan_summary(plan_md_path: Path) -> None:
    """Print a concise plan summary from plan.json alongside PLAN.md."""
    plan_json_path = plan_md_path.parent / "plan.json"
    if not plan_json_path.is_file():
        return

    try:
        plan_data = json.loads(plan_json_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return

    print(f"\nGoal: {plan_data.get('goal', '?')}")

    stories = plan_data.get("stories", [])
    checkpoints = plan_data.get("validation_checkpoints", [])
    checkpoint_map = {cp["after_story"]: cp for cp in checkpoints}

    print(f"\nStories ({len(stories)}):")
    for story in stories:
        sid = story.get("story_id", "?")
        name = story.get("name", "?")
        purpose = story.get("purpose", "")
        scope = story.get("scope", {})
        create = scope.get("create", [])
        modify = scope.get("modify", [])
        cp = checkpoint_map.get(sid)
        cp_count = len(cp.get("checks", [])) if cp else 0

        print(f"\n  {sid}: {name}")
        print(f"    {purpose}")
        if create:
            print(f"    Create: {len(create)} files")
        if modify:
            print(f"    Modify: {len(modify)} files")
        print(f"    Checks: {cp_count} validation commands")


def present_decision_gate(
    plan_md_path: Path,
    verifier_result: VerifierFeedbackArtifact | PlanVerificationResultArtifact,
) -> DecisionGateResult:
    """Present the human with plan summary + verifier report and get a decision."""
    # Display plan location
    print("\n" + "=" * 70)
    print("DECISION GATE")
    print("=" * 70)

    # Show plan summary
    _print_plan_summary(plan_md_path)

    typed_result = (
        verifier_result
        if isinstance(verifier_result, PlanVerificationResultArtifact)
        else None
    )
    typed_feedback = (
        verifier_result
        if isinstance(verifier_result, VerifierFeedbackArtifact)
        else typed_result.verifier_feedback if typed_result is not None else None
    )

    status = (
        typed_result.status
        if typed_result is not None
        else typed_feedback.status
        if typed_feedback is not None
        else "unknown"
    )
    phase_a_errors = (
        typed_result.phase_a_errors
        if typed_result is not None
        else ()
    )
    dispatch_error = (
        typed_result.error
        if typed_result is not None
        else ""
    )

    print(f"\nFull plan: {plan_md_path}")
    print(f"Verifier status: {status}")

    if phase_a_errors:
        print("\nPhase A errors:")
        for err in phase_a_errors:
            print(f"  - {err}")
    elif dispatch_error:
        print(f"\nVerifier error: {dispatch_error}")
        print("(Dimension results unavailable — verifier did not complete)")
    else:
        assert typed_feedback is not None
        dims = _get_dimensions(typed_feedback)
        all_dimensions = [
            "journey_completeness",
            "transition_coverage",
            "intent_alignment",
            "gap_detection",
            "validation_sufficiency",
            "gap_sufficiency",
        ]
        print("\nVerifier dimensions:")
        for dimension in all_dimensions:
            dim = dims.get(dimension, {})
            status = dim.get("status", "unknown") if isinstance(dim, dict) else "unknown"
            if status == "pass":
                icon = "PASS"
            elif status == "fail":
                icon = "FAIL"
            else:
                icon = "SKIP"
            print(f"  [{icon}] {dimension}")

        failed_dims = _extract_dimension_failures(typed_feedback)
        if failed_dims:
            print(f"\nFailed dimensions: {', '.join(failed_dims)}")
            for dim_name in failed_dims:
                dim = dims.get(dim_name, {})
                if not isinstance(dim, dict):
                    continue
                findings = dim.get("findings", dim)
                # Array of finding objects (current verifier format)
                if isinstance(findings, list):
                    must_fix = [
                        f
                        for f in findings
                        if isinstance(f, dict) and f.get("severity") == "must_fix"
                    ]
                    if must_fix:
                        print(f"\n  {dim_name} ({len(must_fix)} must_fix):")
                        for item in must_fix[:5]:
                            print(f"    - {json.dumps(item, ensure_ascii=False)}")
                        if len(must_fix) > 5:
                            print(f"    ... and {len(must_fix) - 5} more")
                # Dict with named keys (legacy format)
                elif isinstance(findings, dict):
                    for key in [
                        "gaps",
                        "uncovered",
                        "unaddressed_requirements",
                        "scope_creep",
                        "weak_checks",
                    ]:
                        items = findings.get(key, [])
                        if items:
                            print(f"\n  {dim_name}.{key}:")
                            for item in items[:3]:
                                if isinstance(item, dict):
                                    print(f"    - {json.dumps(item)}")
                                else:
                                    print(f"    - {item}")
                            if len(items) > 3:
                                print(f"    ... and {len(items) - 3} more")

    print("\nOptions:")
    print("  [a] Approve — proceed to execution")
    print("  [r] Revise  — re-run planner with findings, then re-verify")
    print("  [x] Reject  — exit, planning artefacts not committed")
    print()

    from workflow.cli import flush_stdin

    while True:
        try:
            flush_stdin()
            choice = input("Decision [a/r/x]: ").strip().lower()
        except (EOFError, KeyboardInterrupt):
            print("\nRejected (interrupted)")
            return DecisionGateResult("reject", reason="User interrupted")

        if choice == "a":
            return DecisionGateResult("approve")
        elif choice == "r":
            reason = input("Revision notes (optional): ").strip()
            return DecisionGateResult("revise", reason=reason)
        elif choice == "x":
            reason = input("Rejection reason (optional): ").strip()
            return DecisionGateResult("reject", reason=reason)
        else:
            print("Invalid choice. Enter 'a', 'r', or 'x'.")


