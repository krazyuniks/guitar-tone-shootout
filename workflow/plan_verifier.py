def _write_plan_from_model(plan: Plan, epic_dir: Path) -> None:
    """Write plan.json and PLAN.md from a validated Plan model."""
    PlanArtifact.from_model(plan).write(epic_dir)
    logger.info("Wrote revised plan.json and PLAN.md")


def _regenerate_plan_with_errors(
    epic_dir: Path,
    validation_errors: list[str],
    config: EpicConfig | None = None,
) -> None:
    """Re-invoke the planner with Phase A validation errors.

    Uses a targeted prompt containing only the current plan.json + errors +
    JSON schema (~25K) instead of rebuilding the full planning prompt (~150K).
    """
    request = RevisionRequestArtifact.for_phase_a(
        PlanArtifact.from_path(epic_dir / "plan.json"),
        validation_errors,
    )
    revision_prompt = make_phase_a_revision_prompt(request).text

    planner_model = config.models.planner if config else "opus"

    logger.info(
        "Dispatching %s planner revision (structural errors, %d chars, ~%d tokens)",
        planner_model,
        len(revision_prompt),
        len(revision_prompt) // 4,
    )

    mcp_servers, timeout = get_dispatch_params("planning", config)
    result = dispatch_agent(
        prompt=revision_prompt,
        model=planner_model,
        json_schema=Plan.model_json_schema(),
        cwd=PROJECT_ROOT,
        mcp_servers=mcp_servers,
        timeout=timeout,
        role="planner_revision",
    )

    if not result.success:
        raise PlanGenerationError(
            f"Planner revision dispatch failed (exit_code={result.exit_code}). "
            f"Output: {result.output[:500]}"
        )

    plan = _parse_structured_plan(result)
    _write_plan_from_model(plan, epic_dir)


def _regenerate_plan_with_verifier_feedback(
    epic_dir: Path,
    verifier_feedback: VerifierFeedbackArtifact,
    config: EpicConfig | None = None,
) -> None:
    """Re-invoke the planner with Phase B verifier feedback.

    Uses a targeted prompt containing only the current plan.json + must_fix
    findings + JSON schema (~25K) instead of rebuilding the full planning
    prompt (~150K).
    """
    request = RevisionRequestArtifact.for_phase_b(
        EpicArtifact.from_epic_dir(epic_dir),
        RepoFactsArtifact.from_epic_dir(epic_dir),
        PlanArtifact.from_path(epic_dir / "plan.json"),
        verifier_feedback,
        _read_optional_curation(epic_dir),
    )
    revision_prompt = make_phase_b_revision_prompt(request).text

    planner_model = config.models.planner if config else "opus"

    logger.info(
        "Dispatching %s planner revision (verifier feedback, %d chars, ~%d tokens)",
        planner_model,
        len(revision_prompt),
        len(revision_prompt) // 4,
    )

    mcp_servers, timeout = get_dispatch_params("planning", config)
    result = dispatch_agent(
        prompt=revision_prompt,
        model=planner_model,
        json_schema=Plan.model_json_schema(),
        cwd=PROJECT_ROOT,
        mcp_servers=mcp_servers,
        timeout=timeout,
        role="planner_revision",
    )

    if not result.success:
        raise PlanGenerationError(
            f"Planner revision (verifier feedback) dispatch failed "
            f"(exit_code={result.exit_code}). Output: {result.output[:500]}"
        )

    plan = _parse_structured_plan(result)
    _write_plan_from_model(plan, epic_dir)


