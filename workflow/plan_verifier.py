def verify_plan(
    epic_dir: Path,
    config: EpicConfig | None = None,
) -> VerifierFeedbackArtifact:
    """Run Phase B cross-model verification on the plan.

    Uses config.models.plan_critic if provided, otherwise falls back to codex.
    """
    # Read inputs
    feedback = _verify_plan_artifact(epic_dir, config=config)
    logger.info(
        "Plan verifier result: model=%s, status=%s",
        config.models.plan_critic if config else "opus",
        feedback.status,
    )
    return feedback


def _verify_plan_artifact(
    epic_dir: Path,
    config: EpicConfig | None = None,
) -> VerifierFeedbackArtifact:
    """Run Phase B verification and return a typed verifier feedback artifact."""
    plan_json_path = epic_dir / "plan.json"
    epic_md_path = epic_dir / "EPIC.md"
    repo_facts_path = epic_dir / "repo_facts.json"

    if not plan_json_path.is_file():
        raise PlanVerificationError(f"plan.json not found at {plan_json_path}")
    if not epic_md_path.is_file():
        raise PlanVerificationError(f"EPIC.md not found at {epic_md_path}")
    if not repo_facts_path.is_file():
        raise PlanVerificationError(f"repo_facts.json not found at {repo_facts_path}")

    plan = PlanArtifact.from_path(plan_json_path)
    epic = EpicArtifact.from_epic_dir(epic_dir)
    repo_facts = RepoFactsArtifact.from_path(repo_facts_path)
    curation = _read_optional_curation(epic_dir)

    prompt = make_verifier_prompt(plan, epic, repo_facts, curation).text

    critic_model = config.models.plan_critic if config else "opus"

    logger.info(
        "Dispatching %s verifier (%d chars, ~%d tokens)",
        critic_model,
        len(prompt),
        len(prompt) // 4,
    )

    # Dispatch via critic model (cross-model critique)
    mcp_servers, timeout = get_dispatch_params("critique", config)
    result = dispatch_agent(
        prompt=prompt,
        model=critic_model,
        cwd=PROJECT_ROOT,
        mcp_servers=mcp_servers,
        timeout=timeout,
        role="plan_verifier",
    )

    if not result.success:
        raise PlanVerificationError(
            f"Verifier dispatch failed (exit_code={result.exit_code}). "
            f"Output: {result.output[:500]}"
        )

    # Parse structured output
    return _parse_verifier_result(result.output)


# ---------------------------------------------------------------------------
# Full verification with revision cycle
# ---------------------------------------------------------------------------


def verify_with_revision_cycle(
    epic_dir: Path,
    config: EpicConfig | None = None,
) -> tuple[PlanVerificationResultArtifact, bool]:
    """Run Phase A validation plus a single Phase B critique/revision cycle."""

    # Phase A: Deterministic validation (attempt 1)
    logger.info("Running Phase A validation (attempt 1)...")
    phase_a_result = validate_plan(epic_dir)

    if not phase_a_result.valid:
        logger.warning(
            "Phase A failed with %d errors. Re-invoking planner...",
            len(phase_a_result.errors),
        )

        # Re-invoke planner with validation errors
        try:
            _regenerate_plan_with_errors(epic_dir, phase_a_result.error_messages(), config=config)
        except PlanGenerationError as exc:
            logger.error("Plan regeneration failed: %s", exc)
            return (
                PlanVerificationResultArtifact.from_phase_a_errors(
                    phase_a_result.error_messages()
                ),
                False,
            )

        # Re-run Phase A on revised plan
        logger.info("Running Phase A validation (attempt 2, after planner revision)...")
        phase_a_result = validate_plan(epic_dir)
        if not phase_a_result.valid:
            logger.error(
                "Phase A still fails after planner revision (%d errors). Exiting to human.",
                len(phase_a_result.errors),
            )
            return (
                PlanVerificationResultArtifact.from_phase_a_errors(
                    phase_a_result.error_messages()
                ),
                False,
            )

    logger.info("Phase A passed. Running Phase B verification...")

    # Phase B: AI verification (attempt 1)
    try:
        verifier_feedback = _verify_plan_artifact(epic_dir, config=config)
    except PlanVerificationError as exc:
        logger.error("Phase B dispatch failed: %s", exc)
        return (PlanVerificationResultArtifact.from_error(str(exc)), False)

    if _is_verifier_pass(verifier_feedback):
        logger.info("Phase B passed. Plan verified.")
        result = PlanVerificationResultArtifact.from_verifier_feedback(verifier_feedback)
        return (result, result.passed)

    # Phase B failed — feed verifier output back to planner for revision
    failed_dims = _extract_dimension_failures(verifier_feedback)
    logger.warning(
        "Phase B failed (dimensions: %s). Re-invoking planner with verifier feedback...",
        ", ".join(failed_dims),
    )

    # Hard stop: if verifier reported fail but produced no extractable findings,
    # something went wrong with the invocation (instant return, auth failure,
    # malformed output, etc.). Don't waste money on a blind re-plan.
    if not _has_extractable_findings(verifier_feedback):
        raise PlanVerificationError(
            "Verifier reported fail but contains no extractable must_fix findings. "
            "The verifier may not have run properly. "
            f"Raw result: {json.dumps(verifier_feedback.to_dict())[:2000]}"
        )

    # Snapshot the current (Phase A-passing) plan before revision
    plan_json_path = epic_dir / "plan.json"
    plan_md_path = epic_dir / "PLAN.md"
    original_plan_json = plan_json_path.read_text(encoding="utf-8")
    original_plan_md = plan_md_path.read_text(encoding="utf-8") if plan_md_path.exists() else ""

    try:
        _regenerate_plan_with_verifier_feedback(epic_dir, verifier_feedback, config=config)
    except PlanGenerationError as exc:
        logger.error("Plan regeneration (verifier feedback) failed: %s", exc)
        return (PlanVerificationResultArtifact.from_verifier_feedback(verifier_feedback), False)

    # Re-run Phase A on revised plan (must still pass after revision)
    logger.info("Running Phase A validation (after verifier revision)...")
    phase_a_result = validate_plan(epic_dir)
    if not phase_a_result.valid:
        logger.warning(
            "Phase A fails after verifier revision (%d errors). "
            "Restoring pre-revision plan and continuing with Phase B failure.",
            len(phase_a_result.errors),
        )
        for err in phase_a_result.errors:
            logger.warning("  Phase A error: [%s] %s", err.check, err.message)
        # Restore the original plan that passed Phase A
        plan_json_path.write_text(original_plan_json, encoding="utf-8")
        if original_plan_md:
            plan_md_path.write_text(original_plan_md, encoding="utf-8")
        logger.info("Restored pre-revision plan.json and PLAN.md.")
        return (PlanVerificationResultArtifact.from_verifier_feedback(verifier_feedback), False)

    logger.info(
        "Revised plan passed Phase A revalidation after verifier findings. "
        "Skipping a second Phase B critique and accepting the revised plan."
    )
    return (PlanVerificationResultArtifact.from_revision_success(), True)


