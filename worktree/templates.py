def _get_existing_db_password(env_path: Path) -> str | None:
    """Extract existing DB_PASSWORD from .env file if present.

    Args:
        env_path: Path to .env file

    Returns:
        Existing password or None if not found
    """
    if not env_path.exists():
        return None

    for line in env_path.read_text().splitlines():
        line = line.strip()
        if line.startswith("DB_PASSWORD=") and not line.startswith("#"):
            password = line.split("=", 1)[1].strip()
            if password:
                return password
    return None


def write_worktree_configs(worktree: Worktree, worktree_path: Path) -> None:
    """Write all configuration files for a worktree.

    This function is idempotent:
    - Preserves existing DB_PASSWORD to avoid breaking running databases
    - Only generates new password on fresh setup
    - Safe to call multiple times

    Args:
        worktree: Worktree configuration
        worktree_path: Path to the worktree
    """
    env_path = worktree_path / ".env"
    env_example = worktree_path / ".env.example"

    # CRITICAL: Preserve existing password to avoid breaking running databases
    # Only generate a new password if one doesn't exist
    existing_password = _get_existing_db_password(env_path)
    db_password = existing_password or generate_db_password()

    # Write .env.local (worktree-specific, loaded via env_file in docker-compose.yml)
    env_local_path = worktree_path / ".env.local"
    env_local_content = render_env_local(worktree, db_password)
    env_local_path.write_text(env_local_content)

    # Create .env from example if it doesn't exist
    if not env_path.exists() and env_example.exists():
        import shutil

        shutil.copy(env_example, env_path)

    # Ensure DB_PASSWORD is in .env (only updates if missing or different)
    _update_env_password(env_path, db_password)

    # Ensure Traefik variables are in .env (for docker-compose.traefik.yml)
    _update_env_traefik(env_path, worktree)

    # Write docker-compose.override.yml
    compose_override_path = worktree_path / "docker-compose.override.yml"
    compose_override_content = render_compose_override(worktree)
    compose_override_path.write_text(compose_override_content)

    # Note: nginx.dev.conf is no longer generated - docker-compose.yml now mounts
    # nginx.conf.template directly and uses envsubst at container startup


def _update_env_password(env_path: Path, db_password: str) -> None:
    """Update or add DB_PASSWORD in .env file.

    Args:
        env_path: Path to .env file
        db_password: Generated password to set
    """
    if not env_path.exists():
        # Create minimal .env with just the password
        env_path.write_text(
            f"# Auto-generated database password (do not commit this file)\n"
            f"DB_PASSWORD={db_password}\n"
        )
        return

    # Read existing content
    content = env_path.read_text()
    lines = content.splitlines()

    # Find and update DB_PASSWORD line, or add it
    password_line = f"DB_PASSWORD={db_password}"
    found = False

    for i, line in enumerate(lines):
        # Skip comments and empty lines
        stripped = line.strip()
        if stripped.startswith("DB_PASSWORD="):
            lines[i] = password_line
            found = True
            break
        # Also handle commented out DB_PASSWORD
        if stripped.startswith("# DB_PASSWORD="):
            lines[i] = password_line
            found = True
            break

    if not found:
        # Add after the first comment block or at the top
        # Find first non-comment, non-empty line
        insert_pos = 0
        for i, line in enumerate(lines):
            stripped = line.strip()
            if stripped and not stripped.startswith("#"):
                insert_pos = i
                break
            insert_pos = i + 1

        lines.insert(insert_pos, password_line)
        if insert_pos > 0 and lines[insert_pos - 1].strip():
            lines.insert(insert_pos, "")  # Add blank line before

    env_path.write_text("\n".join(lines) + "\n")


def _update_env_traefik(env_path: Path, worktree: Worktree) -> None:
    """Update or add Traefik variables in .env file.

    These are required for docker-compose.traefik.yml to work correctly.

    Args:
        env_path: Path to .env file
        worktree: Worktree configuration
    """
    if not env_path.exists():
        return  # Should not happen, _update_env_password creates it

    subdomain = _get_traefik_subdomain(worktree)
    router_name = _get_traefik_router_name(worktree)

    content = env_path.read_text()
    lines = content.splitlines()

    # Variables to update/add
    traefik_vars = {
        "GTS_SUBDOMAIN": subdomain,
        "GTS_ROUTER_NAME": router_name,
    }

    # Check which variables need to be added
    for var_name, var_value in traefik_vars.items():
        var_line = f"{var_name}={var_value}"
        found = False

        for i, line in enumerate(lines):
            stripped = line.strip()
            if stripped.startswith(f"{var_name}="):
                lines[i] = var_line
                found = True
                break

        if not found:
            # Add at end of file
            if lines and lines[-1].strip():
                lines.append("")  # Add blank line before if needed
            lines.append(var_line)

    env_path.write_text("\n".join(lines) + "\n")
