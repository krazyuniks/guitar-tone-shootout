# ---------------------------------------------------------------------------
# env.local.sh (secrets, shell-sourced)
# ---------------------------------------------------------------------------


def _parse_shell_exports(path: Path) -> dict[str, str]:
    """Parse a shell file of `export KEY=value` lines into a dict."""
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key:
            values[key] = value
    return values


def _parse_dotenv(path: Path) -> dict[str, str]:
    """Parse a flat KEY=value dotenv file into a dict (no export prefix)."""
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key and value:
            values[key] = value
    return values


def _write_env_local_sh(path: Path, values: dict[str, str]) -> None:
    """Write env.local.sh with shell export lines in the canonical order."""
    lines = [
        "# env.local.sh - GTS project secrets (gitignored, human-managed)",
        "#",
        "# Sourced by .envrc (direnv) and scripts/dc before `docker compose` runs.",
        "# worktree.py seeds missing entries on first setup; it never overwrites",
        "# values you have edited.",
        "",
    ]
    for key in SECRET_KEYS:
        value = values.get(key, "")
        lines.append(f"export {key}={value}")
    # Preserve any unknown keys that were already present.
    extras = {k: v for k, v in values.items() if k not in SECRET_KEYS}
    if extras:
        lines.append("")
        lines.append("# Additional local values")
        for key, value in extras.items():
            lines.append(f"export {key}={value}")
    path.write_text("\n".join(lines) + "\n")


def _ensure_env_local_sh(worktree_path: Path) -> dict[str, str]:
    """Seed env.local.sh on first setup; preserve existing values thereafter.

    Returns the final set of secret values (used to prime POSTGRES on fresh
    databases via compose interpolation of `DB_PASSWORD`).
    """
    target = worktree_path / "env.local.sh"
    current = _parse_shell_exports(target)

    # Migrate from legacy dotenv files if env.local.sh is missing the value.
    legacy: dict[str, str] = {}
    for legacy_name in LEGACY_ENV_FILES:
        legacy.update(_parse_dotenv(worktree_path / legacy_name))

    def take(key: str) -> str:
        return current.get(key) or legacy.get(key) or ""

    values: dict[str, str] = {}
    values["DB_PASSWORD"] = take("DB_PASSWORD") or _generate_db_password()
    values["OAUTH_ENCRYPTION_KEY"] = (
        take("OAUTH_ENCRYPTION_KEY") or _generate_fernet_key()
    )
    values["SECRET_KEY"] = take("SECRET_KEY") or _generate_hex_key()
    values["GTS_ADMIN_PASSWORD"] = take("GTS_ADMIN_PASSWORD")
    values["T3K_API_KEY"] = take("T3K_API_KEY")

    # Carry forward any other keys the user already added to env.local.sh.
    for key, value in current.items():
        if key not in SECRET_KEYS:
            values[key] = value

    _write_env_local_sh(target, values)
    return values


# ---------------------------------------------------------------------------
# Public entry point: write all config files for a worktree
# ---------------------------------------------------------------------------


def write_worktree_configs(worktree: Worktree, worktree_path: Path) -> None:
    """Write .env.worktree, docker-compose.override.yml, seed env.local.sh.

    Idempotent — safe to call multiple times. Migrates legacy .env/.env.local/
    .env.secrets into env.local.sh + .env.worktree on first run, then removes
    the legacy files so only the new sources of truth remain.
    """
    _ensure_env_local_sh(worktree_path)

    env_worktree_path = worktree_path / ".env.worktree"
    env_worktree_path.write_text(render_env_worktree(worktree))

    compose_override_path = worktree_path / "docker-compose.override.yml"
    compose_override_path.write_text(render_compose_override(worktree))

    # Remove legacy dotenvs now that env.local.sh + .env.worktree own the data.
    for legacy_name in LEGACY_ENV_FILES:
        legacy_path = worktree_path / legacy_name
        if legacy_path.exists():
            legacy_path.unlink()
