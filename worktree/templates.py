"""Template management for worktree configuration files.

Generates per-worktree env files in the consolidated env model:

    compose.env           - committed static defaults (not managed here)
    .env.worktree         - gitignored, auto-generated by this module
    env.local.sh          - gitignored, seeded here on first setup (secrets)
    env.local.sh.example  - committed template (not managed here)

Legacy files (`.env`, `.env.local`, `.env.secrets`) are migrated into the new
layout on setup and then removed.
"""

from __future__ import annotations

import base64
import secrets
from datetime import UTC, datetime
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, select_autoescape

from .docker import is_traefik_running
from .registry import Worktree

LEGACY_ENV_FILES = (".env", ".env.local", ".env.secrets")

# Shell-exported secrets managed by env.local.sh. Order is preserved when
# rewriting the file.
SECRET_KEYS: tuple[str, ...] = (
    "DB_PASSWORD",
    "OAUTH_ENCRYPTION_KEY",
    "SECRET_KEY",
    "GTS_ADMIN_PASSWORD",
    "T3K_API_KEY",
)


def _generate_db_password() -> str:
    """Generate a secure random database password."""
    return secrets.token_urlsafe(24)


def _generate_fernet_key() -> str:
    """Generate a URL-safe base64-encoded 32-byte Fernet key."""
    return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()


def _generate_hex_key(nbytes: int = 32) -> str:
    """Generate a hex-encoded random key."""
    return secrets.token_hex(nbytes)


def _get_public_url(worktree: Worktree) -> str:
    """Public URL for the worktree (Traefik HTTPS when running, else localhost)."""
    if is_traefik_running():
        subdomain = _get_traefik_subdomain(worktree)
        return f"https://{subdomain}.tone-shootout.com"
    return f"http://localhost:{worktree.ports.nginx}"


def _get_traefik_subdomain(worktree: Worktree) -> str:
    """Derive Traefik subdomain from the worktree branch."""
    branch = worktree.branch
    if branch == "main":
        return "main"
    if "/" in branch:
        prefix = branch.split("/")[0]
        if prefix.isdigit():
            return prefix
    if "-" in branch:
        prefix = branch.split("-")[0]
        if prefix.isdigit():
            return prefix
    sanitized = "".join(c if c.isalnum() or c == "-" else "-" for c in branch.lower())
    sanitized = sanitized.strip("-")[:20].rstrip("-")
    return sanitized or "main"


def _get_traefik_router_name(worktree: Worktree) -> str:
    return f"gts-{_get_traefik_subdomain(worktree)}"


def _get_compose_file() -> str:
    """Resolve COMPOSE_FILE for the current environment.

    Includes the traefik overlay when Traefik is currently running — matches
    the prior behaviour of `_ensure_compose_file_includes_traefik`.
    """
    parts = ["docker-compose.yml", "docker-compose.override.yml"]
    if is_traefik_running():
        parts.append("docker-compose.traefik.yml")
    return ":".join(parts)


def get_template_env() -> Environment:
    template_dir = Path(__file__).parent / "templates"
    return Environment(
        loader=FileSystemLoader(template_dir),
        autoescape=select_autoescape(),
        trim_blocks=True,
        lstrip_blocks=True,
    )


# ---------------------------------------------------------------------------
# .env.worktree
# ---------------------------------------------------------------------------


def render_env_worktree(worktree: Worktree) -> str:
    """Render .env.worktree content for a worktree."""
    env = get_template_env()
    ctx = {
        "worktree": worktree,
        "generated_at": datetime.now(UTC).isoformat(),
        "public_url": _get_public_url(worktree),
        "subdomain": _get_traefik_subdomain(worktree),
        "router_name": _get_traefik_router_name(worktree),
        "compose_file": _get_compose_file(),
    }
    try:
        template = env.get_template("env.worktree.j2")
    except Exception:
        return _render_env_worktree_inline(**ctx)
    return template.render(**ctx)


