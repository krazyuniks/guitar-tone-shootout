"""Template management for configuration files.

Uses Jinja2 for template rendering with worktree-specific values.
"""

import os
import secrets
from datetime import UTC, datetime
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, select_autoescape

from .config import settings
from .docker import is_traefik_running
from .registry import Worktree


def generate_db_password() -> str:
    """Generate a secure random database password.

    Returns:
        A URL-safe random string suitable for database authentication.
    """
    return secrets.token_urlsafe(24)


def _get_public_url(worktree: Worktree) -> str:
    """Get the public URL for a worktree.

    Uses Traefik HTTPS URL if Traefik is running (server deployment),
    otherwise falls back to localhost with nginx port.

    Args:
        worktree: Worktree configuration

    Returns:
        Public URL (e.g., "https://main.tone-shootout.com" or "http://localhost:9000")
    """
    if is_traefik_running():
        subdomain = _get_traefik_subdomain(worktree)
        return f"https://{subdomain}.tone-shootout.com"
    return f"http://localhost:{worktree.ports.nginx}"


def get_template_env() -> Environment:
    """Get Jinja2 environment for templates.

    Returns:
        Configured Jinja2 Environment
    """
    template_dir = Path(__file__).parent / "templates"
    return Environment(
        loader=FileSystemLoader(template_dir),
        autoescape=select_autoescape(),
        trim_blocks=True,
        lstrip_blocks=True,
    )


def render_env_local(worktree: Worktree, db_password: str | None = None) -> str:
    """Render .env.local template for a worktree.

    Args:
        worktree: Worktree configuration
        db_password: Database password (auto-generated if not provided)

    Returns:
        Rendered .env.local content
    """
    env = get_template_env()

    # Generate password if not provided
    if db_password is None:
        db_password = generate_db_password()

    try:
        template = env.get_template("env.local.j2")
    except Exception:
        # Fallback to inline template if file not found
        return _render_env_local_inline(worktree, db_password)

    return template.render(
        worktree=worktree,
        settings=settings,
        db_password=db_password,
        generated_at=datetime.now(UTC).isoformat(),
        uid=os.getuid(),
        gid=os.getgid(),
        public_url=_get_public_url(worktree),
    )


def render_compose_override(worktree: Worktree) -> str:
    """Render docker-compose.override.yml template for a worktree.

    Args:
        worktree: Worktree configuration

    Returns:
        Rendered docker-compose.override.yml content
    """
    env = get_template_env()

    try:
        template = env.get_template("docker-compose.override.yml.j2")
    except Exception:
        # Fallback to inline template if file not found
        return _render_compose_override_inline(worktree)

    return template.render(
        worktree=worktree,
        settings=settings,
        generated_at=datetime.now(UTC).isoformat(),
        public_url=_get_public_url(worktree),
    )


def _get_traefik_subdomain(worktree: Worktree) -> str:
    """Derive Traefik subdomain from worktree info.

    Returns:
        Subdomain string (e.g., "main", "526", "feature-foo")
    """
    branch = worktree.branch

    # main branch gets "main" subdomain
    if branch == "main":
        return "main"

    # Issue branches (e.g., "526/epic-..." or "42-fix-bug") get issue number
    # Check for "N/..." pattern
    if "/" in branch:
        prefix = branch.split("/")[0]
        if prefix.isdigit():
            return prefix

    # Check for "N-..." pattern at start
    if "-" in branch:
        prefix = branch.split("-")[0]
        if prefix.isdigit():
            return prefix

    # Fallback: sanitize branch name for subdomain (max 20 chars, alphanumeric + hyphen)
    sanitized = "".join(c if c.isalnum() or c == "-" else "-" for c in branch.lower())
    sanitized = sanitized.strip("-")[:20].rstrip("-")
    return sanitized or "main"


def _get_traefik_router_name(worktree: Worktree) -> str:
    """Derive unique Traefik router name from worktree info.

    Returns:
        Router name (e.g., "gts-main", "gts-526")
    """
    subdomain = _get_traefik_subdomain(worktree)
    return f"gts-{subdomain}"


